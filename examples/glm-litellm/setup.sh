#!/usr/bin/env bash
# setup.sh — install LiteLLM and register a "glm" crew backend.
#
# After this, `crew --backend glm mysess "task"` starts a Claude Code session
# driving your GLM (or any OpenAI-compatible) model as a tool-using agent, with
# LiteLLM (auto-started on demand) translating Anthropic <-> OpenAI + tool-calling.
#
# Prereqs: fill in examples/glm-litellm/config.yaml (api_base + model) and export
# GLM_GATEWAY_TOKEN with your upstream gateway token.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CFG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}/claude-crew"
GLM_CFG_DIR="$CFG_HOME/glm-litellm"
BACKEND_DIR="$CFG_HOME/backends"
PORT="${LITELLM_PORT:-4000}"
MIRROR="${PIP_INDEX_URL:-https://pypi.org/simple}"
mkdir -p "$GLM_CFG_DIR" "$BACKEND_DIR"

log(){ echo "[glm-setup] $*" >&2; }

# --- 1) install litellm (idempotent) ---------------------------------------
pick_python(){ for c in python3.12 python3.11 python3.10 python3; do command -v "$c" >/dev/null 2>&1 || continue
  case "$("$c" -c 'import sys;print("%d.%d"%sys.version_info[:2])' 2>/dev/null)" in 3.14|3.15) continue;; esac; echo "$c"; return 0; done; return 1; }
if command -v litellm >/dev/null 2>&1 && litellm --version >/dev/null 2>&1; then
  log "litellm already installed: $(command -v litellm)"
else
  PY=$(pick_python) || { log "no suitable python3 (need 3.10-3.13); skipping litellm install"; PY=""; }
  if [ -n "$PY" ]; then
    pyver=$("$PY" -c 'import sys;print("%d.%d"%sys.version_info[:2])')
    # litellm 1.95 conflicts with fastapi 0.141; pin 1.80.0. py3.8/3.9 need tokenizers<0.21.
    pins="litellm==1.80.0 litellm[proxy]"; case "$pyver" in 3.8|3.9) pins="$pins tokenizers<0.21";; esac
    bsp=""; "$PY" -m pip install --help 2>/dev/null | grep -q break-system-packages && bsp="--break-system-packages"
    log "installing litellm==1.80.0 with $PY (py$pyver) from $MIRROR"
    "$PY" -m pip install --user $bsp -i "$MIRROR" $pins 2>&1 | tail -12 || true
  fi
fi

# --- 2) config.yaml ---------------------------------------------------------
if [ ! -f "$GLM_CFG_DIR/config.yaml" ]; then
  cp "$HERE/config.yaml" "$GLM_CFG_DIR/config.yaml"
  log "wrote $GLM_CFG_DIR/config.yaml — EDIT it: set api_base + model to your gateway"
else
  log "keeping existing $GLM_CFG_DIR/config.yaml"
fi

# --- 3) register the crew backend ------------------------------------------
cat > "$BACKEND_DIR/glm.conf" <<CONF
# crew backend: GLM via LiteLLM. Generated by examples/glm-litellm/setup.sh.
BASE_URL=http://127.0.0.1:$PORT
MODEL=glm-5.2
TOKEN=sk-local-crew
ENSURE_CMD='LITELLM_PORT=$PORT LITELLM_CONFIG=$(printf %q "$GLM_CFG_DIR/config.yaml") $(printf %q "$HERE/ensure-litellm.sh")'
ENV_EXTRA='MAX_THINKING_TOKENS=0'
DANGEROUS=1
CONF
chmod +x "$HERE/ensure-litellm.sh"
log "registered backend 'glm' -> $BACKEND_DIR/glm.conf"

log "done. Set your token (export GLM_GATEWAY_TOKEN=...), then:"
log "  crew --backend glm mysess \"read README.md and summarize it\""
log "  crew attach mysess"
