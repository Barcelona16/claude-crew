# GKD delegation — OPTIONAL crew extension.
# Copy (or symlink) this file into ~/.config/claude-crew/ext/ to enable `crew delegate`
# and `crew gkd-sync`. Core crew (tmux + CCR-routed presets) works without it.
# GKD (https://github.com/alvis-HaoH/gkd) runs one-shot `claude -p --model X` sub-agents.
# Discovery: set GKD_DIR (or GKD_HOME) to your GKD checkout.
# This file is sourced INTO bin/crew, so it may use crew's die/log/load_backend/BACKEND_DIR.
GKD_INSTALL_HINT='Install GKD (git clone https://github.com/alvis-HaoH/gkd) and set GKD_DIR to its path. crew sessions work without GKD.'
gkd_root(){
  local d
  for d in "${GKD_DIR:-}" "${GKD_HOME:-}"; do
    [ -n "$d" ] && [ -f "$d/scripts/gkd-runtime.mjs" ] && { echo "$d"; return 0; }
  done
  return 1
}
# Project crew's backends/*.conf into GKD's config/models.json (crew = source of truth).
crew_gkd_sync(){
  local gkd; gkd=$(gkd_root) || die "GKD not found. $GKD_INSTALL_HINT"
  command -v node >/dev/null 2>&1 || die "node is required to sync GKD's models.json"
  local tmp; tmp=$(mktemp)
  local f name tok _ev
  for f in "$BACKEND_DIR"/*.conf; do
    [ -f "$f" ] || continue
    name=$(basename "$f" .conf); load_backend "$name"
    [ -z "$BK_BASE_URL" ] && continue          # GKD needs a real endpoint; skip plain-Claude backends
    tok="$BK_TOKEN"; [ -n "$BK_TOKEN_CMD" ] && tok=$(bash -c "$BK_TOKEN_CMD" 2>/dev/null)
    if [ -n "$BK_TOKEN_ENV" ]; then _ev="${!BK_TOKEN_ENV-}"; [ -n "$_ev" ] && tok="$_ev"; fi
    printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$BK_MODEL" "$BK_BASE_URL" "$tok" "$BK_ENV_EXTRA" >> "$tmp"
  done
  CREW_TSV="$tmp" CREW_MF="$gkd/config/models.json" node -e '
    const fs=require("fs");
    const lines=fs.readFileSync(process.env.CREW_TSV,"utf8").split("\n").filter(Boolean);
    const models={};
    for(const l of lines){const [name,model,base,token,env]=l.split("\t");
      const e={}; (env||"").split(/\s+/).filter(Boolean).forEach(kv=>{const i=kv.indexOf("=");if(i>0)e[kv.slice(0,i)]=kv.slice(i+1);});
      const m={}; if(model)m.model=model; if(base)m.baseUrl=base; if(token)m.authToken=token; if(Object.keys(e).length)m.env=e;
      models[name]=m;
    }
    fs.writeFileSync(process.env.CREW_MF, JSON.stringify({_comment:"Generated by `crew gkd-sync` from claude-crew backends. Edit crew backends, not this file.",models},null,2)+"\n");
  '
  rm -f "$tmp"
  log "synced $(ls "$BACKEND_DIR"/*.conf 2>/dev/null | wc -l | tr -d ' ') backend(s) -> $gkd/config/models.json"
}
# One-shot programmatic delegation through GKD, on a crew backend.
crew_delegate(){
  local backend="$1"; shift; local task="$*"
  [ "$backend" = default ] && die "delegate needs a backend with a base URL (e.g. --model glm); 'default' is plain Claude."
  [ -n "$task" ] || die "usage: crew delegate --model <name> \"<task>\""
  local gkd; gkd=$(gkd_root) || die "GKD not found. $GKD_INSTALL_HINT"
  load_backend "$backend"
  [ -n "$BK_ENSURE_CMD" ] && { log "ensuring backend '$backend' is up..."; bash -c "$BK_ENSURE_CMD" >&2 || log "WARN: ENSURE_CMD failed (continuing)"; }
  crew_gkd_sync
  log "delegating to '$backend' via GKD..."
  exec node "$gkd/scripts/gkd-runtime.mjs" "--$backend" "$task"
}
